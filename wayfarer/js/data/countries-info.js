export function drivesOnLeft(iso) {
  return LEFT_HAND_TRAFFIC.has(iso);
}

/** Whether travel between two countries requires passport control. */
export function needsPassportControl(fromIso, toIso) {
  if (!fromIso || !toIso || fromIso === toIso) return false;
  if (SCHENGEN.has(fromIso) && SCHENGEN.has(toIso)) return false;
  // Common Travel Area (UK, Ireland): ID checks only.
  if ((fromIso === 'GB' && toIso === 'IE') || (fromIso === 'IE' && toIso === 'GB')) return false;
  return true;
}

/** Whether a customs check applies on arrival. */
export function needsCustoms(fromIso, toIso) {
  if (!fromIso || !toIso || fromIso === toIso) return false;
  return !(EU_CUSTOMS.has(fromIso) && EU_CUSTOMS.has(toIso));
}

export function fuelPrice(iso) {
  return FUEL_USD_PER_L[iso] ?? FUEL_DEFAULT;
}
